import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
const root = new URL("../screenshots/", import.meta.url);
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", (error) => errors.push(String(error)));
page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
const base = process.argv[2] ?? "http://127.0.0.1:8080/";
const flavor = base.includes(":8081") ? "built" : "dev";
const steps = [];
try {
  await page.goto(base);
  await page.waitForTimeout(1200);
  await page.getByRole("button", { name: "Try: Replacement component" }).click();
  await page.waitForFunction(() => (document.querySelector("textarea")?.value.length ?? 0) >= 20);
  await page.getByRole("button", { name: "Sit with this" }).click();
  await page.getByText("The next useful move").waitFor();
  steps.push("new case and result");
  await page.getByText("What happened next?").scrollIntoViewIfNeeded();
  await page.getByText("Record the action and expectation").click();
  await page.getByLabel("Action actually chosen").fill("Wait");
  await page.getByLabel("Expected result").fill("Load reading arrives");
  await page.getByLabel("Revisit date, if useful").fill("2026-09-24");
  await page.getByRole("button", { name: "Keep this plan" }).click();
  await page.getByText("Outcome pending.").waitFor();
  steps.push("plan saved");
  await page.getByText("Record or correct an outcome").click();
  await page.getByLabel("What happened, and what supports it?").fill("Synthetic sensor log showed a load reading.");
  await page.getByLabel("What changed in your view?").fill("Inspect the measured load.");
  await page.getByRole("button", { name: "Keep this outcome" }).click();
  await page.getByText(/Outcome reported/).waitFor();
  steps.push("outcome saved");
  await page.getByText("Edit this case in a new revision").click();
  await page.getByRole("button", { name: "Save new revision" }).click();
  await page.getByText(/Revision history · 2 runs/).waitFor();
  steps.push("revision appended");
  await page.screenshot({ path: join(root.pathname, `enhance-flow-${flavor}-mind-desktop.png`), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth);
  if (mobileOverflow) throw new Error("Mind view overflows mobile width");
  await page.screenshot({ path: join(root.pathname, `enhance-flow-${flavor}-mind-mobile.png`), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole("button", { name: "Self", exact: true }).first().click();
  await page.getByText("Your local data").waitFor();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export all data" }).click();
  const download = await downloadPromise;
  const exported = await download.createReadStream();
  let json = "";
  for await (const chunk of exported) json += chunk.toString();
  const parsed = JSON.parse(json);
  if (parsed.version !== 2 || parsed.data.sittings.length !== 2 || parsed.data.outcomeEvents.length !== 2) throw new Error("Export did not retain revisions and outcomes");
  steps.push("export inspected");
  await page.getByText("Delete one case").click();
  await page.locator("details").filter({ hasText: "Delete one case" }).locator("select").selectOption(parsed.data.situations[0].id);
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "Delete selected case" }).click();
  await page.reload();
  await page.getByRole("button", { name: "Sit", exact: true }).first().click();
  if (await page.getByText("Earlier sittings").count()) throw new Error("Deleted case returned after reload");
  steps.push("case deletion persisted");
  await page.getByRole("button", { name: "Self", exact: true }).first().click();
  await page.getByText("Import a Limen export").click();
  await page.locator('input[type="file"]').setInputFiles({ name: "synthetic-limen.json", mimeType: "application/json", buffer: Buffer.from(json) });
  await page.getByRole("button", { name: "Preview import" }).click();
  await page.getByRole("button", { name: "Apply import" }).click();
  await page.getByText("Import applied.").waitFor();
  steps.push("export reimported after deletion");
  await page.evaluate(() => localStorage.setItem("limen-v1", "{unreadable"));
  await page.reload();
  await page.getByRole("alert").getByText(/Browser storage needs recovery/).waitFor();
  steps.push("corrupt storage recovery visible");
  await page.screenshot({ path: join(root.pathname, `enhance-flow-${flavor}-after-delete.png`), fullPage: true });
  const memoryContext = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  const memoryPage = await memoryContext.newPage();
  memoryPage.on("pageerror", (error) => errors.push(String(error)));
  memoryPage.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await memoryPage.goto(base);
  async function newMemoryCase(prose, family) {
    await memoryPage.getByRole("button", { name: "Sit", exact: true }).first().click();
    await memoryPage.getByLabel("The situation").fill(prose);
    await memoryPage.getByLabel("Case family or project (optional; helps review whether lessons transfer)").fill(family);
    await memoryPage.getByLabel("What better would mean").fill("Check evidence before selecting a reversible action.");
    await memoryPage.getByRole("button", { name: "Sit with this" }).click();
    await memoryPage.getByText("The next useful move").waitFor();
  }
  async function recordSupportingOutcome(evidence) {
    await memoryPage.getByText("Record the action and expectation").click();
    await memoryPage.getByLabel("Expected result").fill("Independent measurement arrives.");
    await memoryPage.getByRole("button", { name: "Keep this plan" }).click();
    await memoryPage.getByText("Record or correct an outcome").click();
    await memoryPage.getByLabel("What happened, and what supports it?").fill(evidence);
    await memoryPage.getByLabel("Does this outcome support the lesson?").selectOption("supports");
    await memoryPage.getByRole("button", { name: "Keep this outcome" }).click();
    await memoryPage.getByText(/Outcome reported/).waitFor();
  }
  await newMemoryCase("The vendor has an incentive and the load was not measured before selection. The team can pause for a measurement.", "purchase-one");
  await recordSupportingOutcome("Synthetic source log for the first family.");
  await memoryPage.getByRole("button", { name: "Keep a repair" }).click();
  await memoryPage.getByText(/Origin needs|Needs a distinct family/).waitFor();
  steps.push("lesson candidate saved");
  await newMemoryCase("A salesperson receives a commission while temperature remains unmeasured in the trial. Pause the trial for evidence.", "experiment-two");
  await recordSupportingOutcome("Synthetic independent log for the second family.");
  await memoryPage.getByRole("button", { name: "Ledger", exact: true }).first().click();
  await memoryPage.getByRole("button", { name: "Promote with two outcomes" }).click();
  await memoryPage.getByText(/Validation: validated/).waitFor();
  steps.push("lesson promoted from distinct outcome-backed families");
  await newMemoryCase("A broker has an incentive and the load was not measured for the proposed order. Ask for the source measurements.", "order-three");
  await memoryPage.getByText("Explore readings, other concerns, and reasoning").click();
  await memoryPage.getByText("Earlier validated lessons · check applicability").click();
  await memoryPage.getByText(/Recorded prerequisites matched/).waitFor();
  steps.push("validated lesson reused with applicability trace");
  await memoryPage.screenshot({ path: join(root.pathname, `enhance-flow-${flavor}-memory.png`), fullPage: true });
  await memoryContext.close();
  const verdict = { ok: !errors.length, steps, errors, exportedCases: parsed.data.situations.length };
  writeFileSync(join(root.pathname, `enhance-flow-${flavor}.json`), JSON.stringify(verdict, null, 2));
  console.log(JSON.stringify(verdict));
  if (errors.length) process.exitCode = 1;
} catch (error) {
  await page.screenshot({ path: join(root.pathname, `enhance-flow-${flavor}-failure.png`), fullPage: true });
  const verdict = { ok: false, steps, errors, failure: String(error), body: (await page.locator("body").innerText()).slice(0, 2000) };
  writeFileSync(join(root.pathname, `enhance-flow-${flavor}.json`), JSON.stringify(verdict, null, 2));
  console.error(JSON.stringify(verdict));
  process.exitCode = 1;
} finally { await browser.close(); }
